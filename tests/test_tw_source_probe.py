def fixture_get(url, params):
    if params:
        return 200, json.dumps({"status": 200, "data": fixture_rows(params["dataset"])}).encode()
    if "encrypt_file" in url:
        return 200, b"annual" if "2026-02" in url else b"interim"
    return 200, b"[]"


def test_free_three_dataset_coverage_never_exports_raw_values():
    calls = []
    def get(url, params):
        calls.append((url, params))
        if params and "dataset" in params:
            rows = [{"date": "2025-12-31", "stock_id": "2330", "type": "Revenue",
                     "value": 987654321, "origin_name": "DO_NOT_EXPORT_RAW_TEXT"}]
            return 200, json.dumps({"status": 200, "data": rows}).encode()
        return 403, b"DO_NOT_EXPORT_BLOCK_PAGE"

    result = probe(get=get, now=NOW)
    assert result["first_seen_at_utc"] == "2026-10-20T00:00:00+00:00"
    assert len(calls) == 7
    assert all(result["sources"][name]["status"] == "available" for name in ("income", "balance", "cashflow"))
    assert result["sources"]["income"]["periods"] == ["2025-12-31"]
    assert result["sources"]["annual_ir"]["status"] == "forbidden"
    assert result["public_numeric_export"] == "not_verified"
    assert result["current_source_acceptance"] == "not_verified"
    assert "987654321" not in json.dumps(result)
    assert "DO_NOT_EXPORT" not in json.dumps(result)


