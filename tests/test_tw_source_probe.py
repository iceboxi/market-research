def test_actual_pdf_parser_reconciles_synthetic_four_page_documents():
    pypdf = pytest.importorskip("pypdf")
    from pypdf.generic import DictionaryObject, NameObject, DecodedStreamObject
    import io

    def make_pdf(kind):
        writer = pypdf.PdfWriter()
        font = writer._add_object(DictionaryObject({NameObject("/Type"): NameObject("/Font"),
            NameObject("/Subtype"): NameObject("/Type1"), NameObject("/BaseFont"): NameObject("/Helvetica")}))
        for text in fixture_pages(kind):
            page = writer.add_blank_page(width=1000, height=1200)
            page[NameObject("/Resources")] = DictionaryObject({NameObject("/Font"):
                DictionaryObject({NameObject("/F1"): font})})
            commands = ["BT /F1 8 Tf 20 1150 Td"]
            for line in text.splitlines():
                escaped = line.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
                commands.append("(" + escaped + ") Tj 0 -12 Td")
            commands.append("ET")
            stream = DecodedStreamObject()
            stream.set_data("\n".join(commands).encode())
            page[NameObject("/Contents")] = writer._add_object(stream)
        buffer = io.BytesIO()
        writer.write(buffer)
        return buffer.getvalue()

    documents = {b"annual": make_pdf(b"annual"), b"interim": make_pdf(b"interim")}
    def get(url, params):
        status, content = fixture_get(url, params)
        return status, documents.get(content, content)
    result = probe(get=get, now=NOW)
    assert result["current_source_acceptance"] == "reconciled_current_sample"


